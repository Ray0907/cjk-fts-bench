"""Statistics behind the README's statements, generated from results/*.json.

  python -m bench.stats > results/stats.md

Same paired test as the leaderboard (bench.compare.paired: 10,000 bootstrap resamples and 10,000 sign flips,
seed 42), so the same pair gives the same numbers in both. Adds what the leaderboard does not show:

- the top system per language and split, and every system's distance from it, with Holm-corrected p-values
  (over all comparisons with the top in that language and split);
- equivalence: "within ±0.01" means the 90% bootstrap CI of the difference lies inside [-0.01, +0.01] (two
  one-sided tests at the 5% level). A difference that is not significant is not called a tie unless it passes this;
- the pairs the README discusses, with 95% and 90% CIs and per-query wins/ties/losses;
- index size ratios under the three measures, and the smallest system under each.
"""
from __future__ import annotations

import sys

from .leaderboard import LANGS, SAME_RANKING_AS, SPLITS, _load, fmt_p, load_runs, sig

MARGIN = 0.01
PAIRS = [
    ("app_bigram_first", "app_bigram"),
    ("app_bigram_edge", "app_bigram"),
    ("app_bigram_first", "app_bigram_edge"),
    ("fts5_cjk", "app_bigram"),
    ("fts5_cjk_unigram", "app_bigram"),
    ("jieba", "app_bigram"),
    ("icu_segmenter", "app_bigram"),
    ("icu_segmenter", "app_bigram_first"),
    ("better_trigram", "app_bigram"),
    ("better_trigram", "app_bigram_first"),
    ("fts5_cjk_qfirst", "fts5_cjk"),
    ("fts5_cjk_qfirst", "app_bigram_first"),
    ("fts5_cjk_qedge", "app_bigram_edge"),
    ("fts5_cjk_qedge", "fts5_cjk_qfirst"),
]
SIZE_PAIRS = [("fts5_cjk", "app_bigram"), ("app_bigram_first", "app_bigram"), ("app_bigram_edge", "app_bigram"),
              ("jieba_big", "jieba")]

_cache: dict = {}


def csig(key, run, a, b):
    k = (key, a, b)
    if k not in _cache:
        _cache[k] = sig(run, a, b)
    return _cache[k]


def holm(ps):
    """Holm step-down adjusted p-values, same order as ps."""
    order = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, running = [0.0] * len(ps), 0.0
    for rank, i in enumerate(order):
        running = max(running, min(1.0, (len(ps) - rank) * ps[i]))
        adj[i] = running
    return adj


def within(r, m=MARGIN):
    lo, hi = r["ci90"]
    return -m < lo and hi < m


def ci(r, key="ci95"):
    lo, hi = r[key]
    return f"[{lo:+.4f}, {hi:+.4f}]"


def main():
    runs = load_runs()
    law = _load("law_substring.json")
    out = ["# Statistics behind the README", "",
           "Generated by `python -m bench.stats` from `results/*.json`. nDCG@10 throughout. Paired bootstrap "
           "(10,000 resamples) and sign-flip randomization test (10,000 flips), seed 42; the smallest possible p is "
           "1/10001, shown as p≤0.0001. **within ±0.01** = the 90% CI of the difference lies inside [-0.01, +0.01] "
           "(equivalence by two one-sided tests at 5%). dev = MIRACL dev queries (used during development); train = "
           "MIRACL train queries (held out).", ""]

    out += ["## Top system and distance from it", ""]
    for lang in LANGS:
        for split, _ in SPLITS:
            run = runs.get((lang, split))
            if not run:
                continue
            key = (lang, split)
            names = [n for n in run["systems"] if n not in SAME_RANKING_AS]
            mean = {n: run["systems"][n]["buckets"]["all"]["ndcg10"] for n in names}
            top = max(names, key=lambda n: mean[n])
            others = [n for n in names if n != top]
            rs = [csig(key, run, top, n) for n in others]
            adj = holm([r["p_value"] for r in rs])
            out += [f"### {lang} {split} (n={run['metadata']['n_queries']}): top `{top}` {mean[top]:.4f}", "",
                    "| system | nDCG@10 | top − system | 95% CI | 90% CI | p | Holm p | within ±0.01 |",
                    "|---|---|---|---|---|---|---|---|"]
            rows = sorted(zip(others, rs, adj), key=lambda x: -mean[x[0]])
            for n, r, a in rows:
                out.append(f"| `{n}` | {mean[n]:.4f} | {r['mean_diff']:+.4f} | {ci(r)} | {ci(r, 'ci90')} | "
                           f"{fmt_p(r['p_value'])} | {a:.4f} | {'yes' if within(r) else 'no'} |")
            ns = [n for n, r, a in rows if a >= 0.05]
            eq = [n for n, r, a in rows if within(r)]
            out += ["", f"Not significantly below the top after Holm correction: "
                    f"{', '.join(f'`{n}`' for n in ns) or 'none'}. Within ±0.01 of the top: "
                    f"{', '.join(f'`{n}`' for n in eq) or 'none'}.", ""]

    out += ["## Pairs discussed in the README", "",
            "| pair | split | lang | n | diff | 95% CI | 90% CI | p | W/T/L | within ±0.01 |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for a, b in PAIRS:
        for split, _ in SPLITS:
            for lang in LANGS:
                run = runs.get((lang, split))
                if not run or a not in run["systems"] or b not in run["systems"]:
                    continue
                r = csig((lang, split), run, a, b)
                out.append(f"| `{a}` − `{b}` | {split} | {lang} | {r['n']} | {r['mean_diff']:+.4f} | {ci(r)} | "
                           f"{ci(r, 'ci90')} | {fmt_p(r['p_value'])} | {r['wins']}/{r['ties']}/{r['losses']} | "
                           f"{'yes' if within(r) else 'no'} |")

    out += ["", "## Index size", "",
            "MB = 10^6 bytes. index only = FTS5 `content=''`; index + raw = index only plus one plain table of the "
            "original text; default = the FTS5 table with its stored copy (the measure used before 2026-11).", "",
            "| A vs B | corpus | index only | index + raw | default |", "|---|---|---|---|---|"]
    srcs = [("law", law)] + [(f"{lang} train", runs.get((lang, "train"))) for lang in LANGS]
    srcs = [(label, s) for label, s in srcs if s and s["metadata"].get("raw_table_bytes")]
    for a, b in SIZE_PAIRS:
        for label, s in srcs:
            sa, sb = s["systems"].get(a), s["systems"].get(b)
            if not sa or not sb or "index_bytes_contentless" not in sa:
                continue
            raw = s["metadata"]["raw_table_bytes"]
            pct = lambda x, y: f"{100 * (x / y - 1):+.1f}%"  # noqa: E731
            out.append(f"| `{a}` vs `{b}` | {label} | "
                       f"{pct(sa['index_bytes_contentless'], sb['index_bytes_contentless'])} | "
                       f"{pct(sa['index_bytes_contentless'] + raw, sb['index_bytes_contentless'] + raw)} | "
                       f"{pct(sa['index_bytes'], sb['index_bytes'])} |")
    out += ["", "Smallest index per measure (two smallest, MB):", ""]
    for label, s in srcs:
        raw = s["metadata"]["raw_table_bytes"]
        sysd = {n: v for n, v in s["systems"].items() if "index_bytes_contentless" in v}
        parts = []
        for mname, f in (("index only", lambda v: v["index_bytes_contentless"]),
                         ("index + raw", lambda v: v["index_bytes_contentless"] + raw),
                         ("default", lambda v: v["index_bytes"])):
            best = sorted(sysd, key=lambda n: f(sysd[n]))[:2]
            parts.append(f"{mname}: " + ", ".join(f"`{n}` {f(sysd[n]) / 1e6:.1f}" for n in best))
        out.append(f"- {label}: " + "; ".join(parts))
    print("\n".join(out))


if __name__ == "__main__":
    sys.exit(main())
