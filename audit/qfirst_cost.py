"""Cost of fts5_cjk_qfirst / fts5_cjk_qedge against fts5_cjk on the MIRACL train queries.

  python audit/qfirst_cost.py > audit/qfirst/cost.md

- Query size: mean number of distinct ranking terms per query, computed now with each system's query_tokens()
  on the query texts stored in results/miracl_<lang>_train.json (needs ext/build/fts5_cjk.so).
- Latency: p50 and p95 ratios against fts5_cjk within one run, from the experiment's own result files
  (audit/qfirst/qfirst_miracl_<lang>_train.json: fts5_cjk, the two variants and app_bigram_first run together).
  One run in a VM; only the ratios are meaningful.
"""
import json
import os
import sqlite3
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.chdir(ROOT)
from bench.systems import SYSTEMS  # noqa: E402

NAMES = ("fts5_cjk", "fts5_cjk_qfirst", "fts5_cjk_qedge", "app_bigram_first")
out = ["# Cost of the fts5-cjk ranking-query variants (MIRACL train)", "",
       "Generated by `python audit/qfirst_cost.py`. Terms: mean distinct ranking terms per query (query_tokens()). "
       "Latency: ratio to fts5_cjk within the experiment's single run (audit/qfirst/qfirst_miracl_<lang>_train.json).", "",
       "| lang | queries | mean terms fts5_cjk → qfirst → qedge | p50 ×, qfirst / qedge / app_bigram_first | "
       "p95 ×, qfirst / qedge / app_bigram_first |", "|---|---|---|---|---|"]
for lang in ("zh", "ja", "ko"):
    res = json.load(open(f"results/miracl_{lang}_train.json", encoding="utf-8"))
    qs = [q["query"] for q in res["systems"]["fts5_cjk"]["queries"]]
    conn = sqlite3.connect(":memory:")
    SYSTEMS["fts5_cjk"].setup(conn)
    terms = {n: sum(len(SYSTEMS[n].query_tokens(conn, q)) for q in qs) / len(qs) for n in NAMES[:3]}
    exp = json.load(open(f"audit/qfirst/qfirst_miracl_{lang}_train.json", encoding="utf-8"))["systems"]
    lat = {n: exp[n]["buckets"]["all"] for n in NAMES}
    r = lambda n, k: lat[n][k] / lat["fts5_cjk"][k]  # noqa: E731
    out.append(f"| {lang} | {len(qs)} | {terms['fts5_cjk']:.2f} → {terms['fts5_cjk_qfirst']:.2f} → "
               f"{terms['fts5_cjk_qedge']:.2f} | "
               + " / ".join(f"×{r(n, 'p50_ms'):.2f}" for n in NAMES[1:]) + " | "
               + " / ".join(f"×{r(n, 'p95_ms'):.2f}" for n in NAMES[1:]) + " |")
print("\n".join(out))
